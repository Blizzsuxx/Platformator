#include <SDL3/SDL.h>

namespace platformator_editor
{
inline constexpr std::size_t ThumbnailMaxDimension = 256;
inline constexpr std::size_t ThumbnailMaxEntries = 256;
inline constexpr std::uint64_t ThumbnailMaxRetainedBytes = 64ULL * 1024ULL * 1024ULL;
inline constexpr std::uint64_t ThumbnailMaxOutputSurfaceBytes =
    ThumbnailMaxDimension * ThumbnailMaxDimension * 4ULL;
inline constexpr std::size_t ThumbnailMaxPendingPaths = 64;
inline constexpr std::uint64_t ThumbnailMaxCompletedBytes = 8ULL * 1024ULL * 1024ULL;
inline constexpr std::size_t ThumbnailMaxPendingReplicas = ThumbnailMaxEntries * 8;

struct ThumbnailCacheStats
{
    std::size_t entries = 0;
    std::uint64_t retainedBytes = 0;
    std::size_t pendingPaths = 0;
    std::uint64_t completedBytes = 0;
    std::size_t framePins = 0;
    std::size_t staleEntries = 0;
    std::size_t rendererReplicas = 0;
    bool running = false;
    bool ownerThreadViolation = false;
};

class ThumbnailCache
{
  public:
    ThumbnailCache();
    ~ThumbnailCache();
    ThumbnailCache(const ThumbnailCache &) = delete;
    ThumbnailCache &operator=(const ThumbnailCache &) = delete;

    // Requests are generated by visible Project tiles, so queue order is
    // visible-first. The return value is last-good content, or null while the
    // first preparation is pending/unsupported.
    SDL_Texture *request(const std::filesystem::path &path, SDL_Renderer *renderer = nullptr);
    SDL_Texture *find(const std::filesystem::path &path, SDL_Renderer *renderer = nullptr) const noexcept;
    bool stale(const std::filesystem::path &path) const noexcept;
    std::pair<int, int> source_dimensions(const std::filesystem::path &path) const noexcept;
    std::pair<float, float> source_to_thumbnail_scale(
        const std::filesystem::path &path, SDL_Renderer *renderer = nullptr) const noexcept;
    std::string failure_message(const std::filesystem::path &path) const;

    // Must run on the owning renderer thread. Uploads only completed immutable
    // surfaces; workers never create SDL_Texture objects.
    void poll_uploads(SDL_Renderer *renderer);
    void set_wake_callback(std::function<void()> callback);
    void invalidate(const std::filesystem::path &path, bool subtree = false,
                    std::uint64_t eventSequence = 0);
    void clear(SDL_Renderer *renderer) noexcept;
    void release_renderer(SDL_Renderer *renderer) noexcept;
    void end_frame() noexcept;
    ThumbnailCacheStats stats() const noexcept;

  private:
    friend struct ThumbnailCacheTestProbe;

    struct Entry
    {
        struct Replica
        {
            SDL_Texture *texture = nullptr;
            std::uint64_t bytes = 0;
        };
        SDL_Surface *pixels = nullptr;
        std::uint64_t pixelBytes = 0;
        std::map<SDL_Renderer *, Replica> replicas;
        std::uint64_t bytes = 0;
        std::uint64_t revision = 0;
        std::uint64_t lastUse = 0;
        int sourceWidth = 0;
        int sourceHeight = 0;
        bool stale = false;
        bool failed = false;
        bool demandedThisFrame = false;
        bool demandedPreviousFrame = false;
        std::uint64_t lastInvalidationSequence = 0;
        std::string message;
    };
    struct Request
    {
        std::filesystem::path path;
        std::string key;
        std::uint64_t revision = 0;
        std::uint64_t cacheGeneration = 0;
    };
    struct Result
    {
        Request request;
        SDL_Surface *surface = nullptr;
        int sourceWidth = 0;
        int sourceHeight = 0;
        std::uint64_t byteCost = 0;
        std::string message;
        ~Result();
        Result() = default;
        Result(const Result &) = delete;
        Result &operator=(const Result &) = delete;
        Result(Result &&other) noexcept;
        Result &operator=(Result &&other) noexcept;
    };
    struct ReplicaRequest
    {
        std::string key;
        SDL_Renderer *renderer = nullptr;
        std::uint64_t revision = 0;
        std::uint64_t cacheGeneration = 0;
    };

    static std::string key_for(const std::filesystem::path &path);
    bool owner_thread_ok() const noexcept;
    void enqueue_locked(const std::filesystem::path &path, const std::string &key,
                        Entry &entry);
    void enqueue_replica_locked(const std::string &key, SDL_Renderer *renderer,
                                const Entry &entry);
    void start_next_locked();
    bool make_room_for_locked(std::uint64_t bytes, const std::string &protectedKey);

    mutable std::mutex mutex_;
    const std::thread::id ownerThread_;
    mutable bool ownerThreadViolation_ = false;
    std::map<std::string, Entry> entries_;
    std::deque<Request> pending_;
    std::deque<ReplicaRequest> pendingReplicas_;
    std::optional<Request> runningRequest_;
    std::optional<Result> completed_;
    std::set<std::string> framePins_;
    oneapi::tbb::task_group tasks_;
    SDL_Renderer *ownerRenderer_ = nullptr;
    std::uint64_t cacheGeneration_ = 1;
    std::uint64_t logicalClock_ = 0;
    std::uint64_t retainedBytes_ = 0;
    std::uint64_t completedBytes_ = 0;
    std::uint64_t uploadingBytes_ = 0;
    bool running_ = false;
    bool stopping_ = false;
    std::function<void()> wakeCallback_;
    // Captured into the worker request at dispatch time. Set only by the
    // focused deterministic cache regression test.
    std::function<void(const std::filesystem::path &)> afterPreparationTestHook_;
};
} // namespace platformator_editor
